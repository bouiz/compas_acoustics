"""reStructuredText for the generated pages."""

from __future__ import annotations

import re
from pathlib import Path
from typing import Callable

from .examples import Example
from .examples import walkthrough as read_walkthrough
from .specs import Component
from .specs import Port

GENERATED = "\n.. This page is generated by docs/_ext/ghcomponents; edit its sources, not this file.\n"


def escape(text: str) -> str:
    """Text that renders literally in reStructuredText."""
    return re.sub(r"([\\*`_|])", r"\\\1", str(text))


def title(text: str, char: str = "=") -> str:
    return "{}\n{}\n".format(text, char * len(text))


def first_sentence(text: str) -> str:
    match = re.match(r"(.+?\.)(\s|$)", text.strip(), re.S)
    return match.group(1) if match else text.strip()


def _table(header: list[str], rows: list[list[str]], widths: list[int]) -> str:
    lines = [".. list-table::", "   :header-rows: 1", "   :widths: " + " ".join(str(w) for w in widths), ""]
    for row in [header] + rows:
        lines.append("   * - " + row[0])
        lines += ["     - " + cell for cell in row[1:]]
    return "\n".join(lines) + "\n"


def _input_row(p: Port) -> list[str]:
    description = escape(p.description)
    if p.choices:
        description += " Choices: " + ", ".join(escape(c) for c in p.choices) + "."
    if p.optional:
        description += " *Optional.*"
    default = "" if p.default is None else "``{}``".format(p.default)
    return ["``{}``".format(p.name), escape(p.type_hint or ""), p.access, default, description.strip()]


def component_page(c: Component, *, image: str, icon: str, notes: Path | None, used_in: list[str],
                   python: str | None) -> str:
    parts = [
        ".. _gh-{}:\n".format(c.key),
        title(c.name),
        ".. image:: {}\n   :width: 48px\n   :alt: {} icon\n".format(icon, escape(c.name)),
        "{} · {}\n".format(escape(c.subcategory), escape(c.nickname)),
        escape(c.description) + "\n",
        ".. image:: {}\n   :alt: {} on the Grasshopper canvas\n".format(image, escape(c.name)),
        title("Inputs", "-"),
    ]
    if c.inputs:
        parts.append(_table(["Name", "Type", "Access", "Default", "Description"],
                            [_input_row(p) for p in c.inputs], [15, 10, 8, 10, 57]))
    else:
        parts.append("None.\n")
    parts.append(title("Outputs", "-"))
    if c.outputs:
        parts.append(_table(["Name", "Description"],
                            [["``{}``".format(p.name), escape(p.description)] for p in c.outputs], [20, 80]))
    else:
        parts.append("None.\n")
    if notes is not None:
        parts += [title("Notes", "-"), ".. include:: {}\n".format(Path(notes).as_posix())]
    if used_in:
        parts += [title("Used in", "-"), "".join("* :doc:`../examples/{}`\n".format(n) for n in used_in)]
    parts.append(title("Python equivalent", "-"))
    parts.append(":obj:`{}`\n".format(python) if python else "No Python equivalent (Grasshopper only).\n")
    return "\n".join(parts) + GENERATED


def overview_page(components: list[Component], order: list[str], icon_for: Callable[[Component], str]) -> str:
    parts = [title("Components"),
             "Every component of the plugin, by ribbon panel. Each page lists its inputs and outputs.\n"]
    for subcategory in order:
        members = [c for c in components if c.subcategory == subcategory]
        if not members:
            continue
        parts.append(title(subcategory, "-"))
        cards = [".. grid:: 2 3 4 4", "   :gutter: 2", ""]
        for c in members:
            cards += [
                "   .. grid-item-card:: {}".format(escape(c.name)),
                "      :link: {}".format(c.key),
                "      :link-type: doc",
                "      :img-top: {}".format(icon_for(c)),
                "",
                "      ``{}`` · {}".format(c.nickname, escape(first_sentence(c.description))),
                "",
            ]
        parts.append("\n".join(cards))
    parts.append(".. toctree::\n   :hidden:\n\n" + "".join("   {}\n".format(c.key) for c in components))
    return "\n".join(parts) + GENERATED


def _indent(text: str) -> str:
    return "".join("    " + line if line.strip() else "\n" for line in text.splitlines(True))


def python_example_page(ex: Example, title_text: str, body: str, figures: list[str], stdout: str | None) -> str:
    parts = [".. _example-py-{}:\n".format(ex.name), title(title_text), body + "\n"]
    if ex.ghx is not None:
        parts.append("The same example in Grasshopper: :doc:`/grasshopper/examples/{}`.\n".format(ex.name))
    parts.append(".. literalinclude:: /../examples/{}.py\n   :language: python\n".format(ex.name))
    if figures or stdout:
        parts.append(title("Output", "-"))
        parts += [".. image:: {}\n".format(f) for f in figures]
        if stdout:
            parts.append("::\n\n" + _indent(stdout))
    return "\n".join(parts) + GENERATED


def ghx_example_page(ex: Example, walkthrough: Path, download: str, canvas: str, viewport: str) -> str:
    title_text, body = read_walkthrough(walkthrough)
    intro, _, steps = body.partition("\n\n")
    parts = [
        ".. _example-gh-{}:\n".format(ex.name),
        title(title_text),
        intro + "\n",
        "Download the definition: :download:`{}.ghx <{}>`\n".format(ex.name, download),
        ".. image:: {}\n   :alt: The definition on the Grasshopper canvas\n".format(canvas),
        ".. image:: {}\n   :alt: The Rhino viewport\n".format(viewport),
    ]
    if steps.strip():
        parts += [title("Walkthrough", "-"), steps.strip() + "\n"]
    if ex.py is not None:
        parts.append("The same example in Python: :doc:`/python/examples/{}`.\n".format(ex.name))
    return "\n".join(parts) + GENERATED


def examples_index(title_text: str, names_titles: list[tuple[str, str]]) -> str:
    parts = [title(title_text), "".join("* :doc:`{}`\n".format(name) for name, _ in names_titles)]
    parts.append(".. toctree::\n   :hidden:\n\n" + "".join("   {}\n".format(name) for name, _ in names_titles))
    return "\n".join(parts) + GENERATED
