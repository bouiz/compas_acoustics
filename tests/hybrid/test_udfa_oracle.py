"""UDFA and the three-sided barrier against the authors' toolbox and BTMS (EDtoolbox).

Single wedge (Kirsch and Ewert 2023), fixture tests/data/udfa_single_oracle.mat.
The fixture is generated by MATLAB scripts kept outside the repository
(validation/diffraction/oracle in a local working copy); the geometries
follow Kirsch and Ewert (2023), Sec. V.

Open gap, apex off the physical edge: the gates against BTMS pass only on the
"no worse than the authors' toolbox" clause. wedge/off/view: ours 10.78 dB,
toolbox 10.56 dB, Table I 5.10 dB. wedge/off/sz_rz: ours 4.94 dB, toolbox
4.65 dB, Table I 3.04 dB. Our off-edge branch follows Sec. III-C/D as written
(higher cutoff for the fade); the toolbox departs from it. The Table I gap is
open.

Regenerate (10 cases per group, 180 cases, seed 20261003; MATLAB R2025b with
EDtoolbox v0.504 and the UDFA toolbox v0.90 in $HYBRID_RIR_EXTERNAL)::

    cd validation/diffraction/oracle
    python make_single_cases.py 10 20261003 cases.mat
    matlab -batch "addpath('..'); udfa_single_oracle('cases.mat', 'out.mat')"

then merge: load both .mat files, add p_udfa and p_btms from out.mat to the
fields of cases.mat, and savemat the result to
tests/data/udfa_single_oracle.mat.

Three-sided barrier (Kirsch and Ewert 2024) against second-order BTMS and the
UDFA toolbox, fixture tests/data/double_edge_oracle.mat.

Open gap (decision D5): the 10 m single-shadow groups miss Table 2, 2.79 dB
(square) and 2.53 dB (slanted) against 1.16 and 0.89 dB. beta = 1 and no
low-frequency gain compensation are allowed by Sec. 3.3.1 "at the expense of
precision in the single SZ and VZ", and Sec. 3.3.2 notes that at d_w = 10 m the
modified exterior angle should not be applied at high frequencies. Both are
strict expected failures below.

Regenerate (10 cases per group plus 6 fixed cases, 126 cases, seed 20261003;
MATLAB R2025b with EDtoolbox v0.504 and the UDFA toolbox v0.90 in
$HYBRID_RIR_EXTERNAL; about 10 min)::

    cd validation/diffraction/oracle
    python make_double_cases.py 10 20261003 cases.mat
    matlab -batch "addpath('..'); double_edge_oracle('cases.mat', 'out.mat')"

then merge: load both .mat files, add p_btms, p_udfa and walltime from out.mat
to the fields of cases.mat, and savemat the result to
tests/data/double_edge_oracle.mat. The toolbox column (p_udfa, finite only for
the 6 fixed 270/270 deg, phi = 90 deg cases) came from a separate re-run of
getDoubleEdge on those 6 cases after its receiver angle was changed to
theta_w2 - theta_r2; double_edge_oracle.m now passes that angle, so one run
gives both columns.

Ported from hybrid-rir (gpapadimitri/hybrid-rir @ a272da7, tests/test_udfa_oracle.py).
"""

from pathlib import Path

import numpy as np
import pytest
from scipy.io import loadmat

from compas_acoustics.hybrid.udfa import (
    DoubleEdgePath,
    WedgePath,
    double_edge_terms,
    udfa_transfer,
)

C = 344.0  # the UDFA toolbox hard-codes 344 m/s
DATA = loadmat(Path(__file__).parent / "data" / "udfa_single_oracle.mat", squeeze_me=True)

# Kirsch and Ewert (2023) Table I, average relative error re BTMS in dB, UDFA
# (not IIR) entries; shadow and reflection zone pooled, as in the paper.
TABLE_I = {
    ("knife", "inf", "sz_rz"): 0.05, ("knife", "inf", "view"): 0.13,
    ("knife", "on", "sz_rz"): 0.39, ("knife", "on", "view"): 0.27,
    ("knife", "off", "sz_rz"): 2.68, ("knife", "off", "view"): 3.63,
    ("wedge", "inf", "sz_rz"): 0.10, ("wedge", "inf", "view"): 0.42,
    ("wedge", "on", "sz_rz"): 0.39, ("wedge", "on", "view"): 0.67,
    ("wedge", "off", "sz_rz"): 3.04, ("wedge", "off", "view"): 5.10,
}
DATA_BARRIER = loadmat(Path(__file__).parent / "data" / "double_edge_oracle.mat", squeeze_me=True)

# Kirsch and Ewert (2024) Table 2, average relative error of UDFA re 2nd-order BTMS, dB
TABLE_2 = {
    ("0.1", "square", "single_shadow"): 0.82, ("0.1", "square", "double_shadow"): 0.87,
    ("1", "square", "single_shadow"): 1.22, ("1", "square", "double_shadow"): 0.71,
    ("10", "square", "single_shadow"): 1.16, ("10", "square", "double_shadow"): 0.64,
    ("0.1", "slanted", "single_shadow"): 0.74, ("0.1", "slanted", "double_shadow"): 0.77,
    ("1", "slanted", "single_shadow"): 1.06, ("1", "slanted", "double_shadow"): 0.70,
    ("10", "slanted", "single_shadow"): 0.89, ("10", "slanted", "double_shadow"): 0.69,
}
# beta = 1 and no low-frequency compensation (decision D5) cost accuracy in
# the single shadow zone, which the paper's full method does not pay
TOLERANCE = {"double_shadow": 0.5, "single_shadow": 1.0}


def ours(k):
    f = DATA["freq"]
    path = WedgePath(*(float(DATA[n][k]) for n in (
        "theta_w", "theta_s", "theta_r", "r_s", "r_r", "z_s", "z_r", "length")))
    d = path.d_constrained
    return np.exp(-2j * np.pi * f * d / C) / d * udfa_transfer(path, f, c=C)


def db(x):
    return 20 * np.log10(np.abs(x))


def test_matches_the_authors_toolbox():
    # The authors' MATLAB toolbox (Zenodo 10.5281/zenodo.13771101) is the exact
    # reference for infinite edges and for an apex on the edge. For an apex off
    # the edge its implementation departs from Sec. III-C/D of the paper: it
    # takes the fade cutoff from the lowest underlying term instead of the
    # highest, normalizes by the distance via the unconstrained apex, and uses
    # a corner-equivalent time. There the paper is the reference, and those
    # cases are gated against BTMS below.
    worst = 0.0
    for k, g in enumerate(DATA["group"]):
        if g.split("/")[1] == "off":
            continue
        theirs = DATA["p_udfa"][k]
        audible = np.abs(theirs) > 1e-6 * np.abs(theirs).max()
        worst = max(worst, np.max(np.abs(db(ours(k))[audible] - db(theirs)[audible])))
    assert worst <= 0.01, f"largest deviation {worst:.3f} dB"


def group_error(source):
    errors = {}
    for k, g in enumerate(DATA["group"]):
        kind, length, zone = g.split("/")
        key = (kind, length, "view" if zone == "view" else "sz_rz")
        got = ours(k) if source == "ours" else DATA["p_udfa"][k]
        errors.setdefault(key, []).append(np.mean(np.abs(db(got) - db(DATA["p_btms"][k]))))
    return {key: float(np.mean(v)) for key, v in errors.items()}


@pytest.mark.parametrize("key", sorted(TABLE_I))
def test_error_re_btms_is_that_of_table_i(key):
    paper = TABLE_I[key]
    got = group_error("ours")[key]
    theirs = group_error("toolbox")[key]
    # 10-20 cases per group here against 10000 in the paper; the bar is the
    # larger of the paper's level and the authors' toolbox on the same cases
    bar = max(paper + max(0.3, 0.5 * paper), theirs + 0.3)
    assert got <= bar, f"{key}: {got:.2f} dB, toolbox {theirs:.2f} dB, paper {paper} dB"


# Three-sided barrier


def ours_barrier(k):
    f = DATA_BARRIER["freq"]
    path = DoubleEdgePath(
        float(DATA_BARRIER["theta_w1"][k]), float(DATA_BARRIER["theta_w2"][k]), float(DATA_BARRIER["width"][k]),
        np.array([DATA_BARRIER["sx"][k], DATA_BARRIER["sy"][k]]), np.array([DATA_BARRIER["rx"][k], DATA_BARRIER["ry"][k]]),
        float(DATA_BARRIER["phi"][k]))
    out = np.zeros(f.size, dtype=complex)
    for t in double_edge_terms(path, c=C):
        out += np.exp(-2j * np.pi * f * t.length / C) / t.length * t.transfer(f)
    return out


D5_GAP = pytest.mark.xfail(
    strict=True,
    reason="decision D5: beta = 1 and no low-frequency compensation (Kirsch and Ewert 2024 "
    "Sec. 3.3.1, 'at the expense of precision in the single SZ and VZ'); Sec. 3.3.2: at "
    "d_w = 10 m the modified exterior angle should not be applied at high frequencies; "
    "measured 2.79 / 2.53 dB vs Table 2 1.16 / 0.89 dB")
OPEN_GAPS = {("10", "square", "single_shadow"), ("10", "slanted", "single_shadow")}


@pytest.mark.parametrize(
    "key",
    [pytest.param(k, marks=D5_GAP) if k in OPEN_GAPS else k for k in sorted(TABLE_2)])
def test_error_re_btms_is_that_of_table_2(key):
    errs = [np.mean(np.abs(db(ours_barrier(k)) - db(DATA_BARRIER["p_btms"][k])))
            for k, g in enumerate(DATA_BARRIER["group"]) if tuple(g.split("/")) == key]
    got = float(np.mean(errs))
    assert got <= TABLE_2[key] + TOLERANCE[key[2]], f"{key}: {got:.2f} dB, paper {TABLE_2[key]} dB"


def test_close_to_the_authors_toolbox_in_the_double_shadow_zone():
    errs = []
    for k, g in enumerate(DATA_BARRIER["group"]):
        theirs = DATA_BARRIER["p_udfa"][k]
        if g.endswith("double_shadow") and np.all(np.isfinite(theirs)):
            errs.append(np.mean(np.abs(db(ours_barrier(k)) - db(theirs))))
    if not errs:
        pytest.skip("no 270/270 deg, phi = 90 deg double-shadow cases in the fixture")
    assert np.mean(errs) <= 1.0
