"""BTMS kernels against EDtoolbox v0.504 (Svensson).

tests/data/btms_fd.mat holds the second-order frequency-domain reference of
three boxes and a triangular prism (validation/btms/fd_reference.m, EDmain_convex
with docalctf = 1 and difforder = 2, 1/3-octave values averaged per octave).
Fields: ref_db (case, octave 63 Hz-8 kHz), 10 log10 of the mean |H|^2 over the
three 1/3-octave frequencies f3 of each octave (f3 holds the 24, in order);
td_db (case, octave), the toolbox's own time-domain second order (fd_td.m,
docalcir = 1) as 10 log10 of the mean |FFT|^2 over the octave's bins (n = 2^14,
48 kHz), the definition the test uses for our response
(validation/btms/fd_fixture_td.py). Gates: ours against td_db within 0.1 dB,
63 Hz-8 kHz; ours at f3 against ref_db within 0.5 dB, 63 Hz-4 kHz. Above 4 kHz
and in octave bins the toolbox's time domain itself departs from its frequency
domain (element size c / fs), so the FD gate stops there.

The fixtures tests/data/btms_first.mat and btms_second.mat are generated by
MATLAB scripts kept outside the repository (validation/btms in a local
working copy): make_cases.py N1=240 N2=80 seed 20261006, then btms_oracle.m
with EDtoolbox v0.504 and MATLAB R2025b.

Ported from hybrid-rir (gpapadimitri/hybrid-rir @ 8a70661, tests/test_btms_oracle.py).
"""

from pathlib import Path

import numpy as np
from scipy.io import loadmat

from compas_acoustics.hybrid.btms import (
    _coordtrans1,
    _quadstep,
    betaoverml,
    element_grid,
    wedge1st_ir,
    wedge2nd_ir,
)
from compas_acoustics.hybrid.diffraction import Edge, btms_paths, encode_btms, toolbox_cyl
from compas_acoustics.hybrid.bands import BANDS
from _compat import Material, MeshGeometry, RoomSpec

DATA = Path(__file__).parent / "data"
FIRST = loadmat(DATA / "btms_first.mat", squeeze_me=True)
SECOND = loadmat(DATA / "btms_second.mat", squeeze_me=True)
FD = DATA / "btms_fd.mat"
PLATE = DATA / "btms_plate.mat"


def _case(k):
    rs, rr, zs, zr = (float(FIRST[n][k]) for n in ("rs", "rr", "zs", "zr"))
    za = (rs * zr + rr * zs) / (rs + rr)
    return rs, rr, zs - za, zr - za, float(FIRST["ny"][k]), FIRST["sinnyfivec"][k], FIRST["cosnyfivec"][k]


def test_betaoverml_matches_the_toolbox():
    for k in range(FIRST["rs"].size):
        rs, rr, zs, zr, nu, s, c = _case(k)
        z = FIRST["zprobe"][k]
        got = betaoverml(z, rs, rr, zs, zr, nu, s, c)
        m = np.sqrt((z - zs) ** 2 + rs**2)
        l = np.sqrt((z - zr) ** 2 + rr**2)
        y = (m * l + (z - zs) * (z - zr)) / (rs * rr)
        # y - 1 cancels near the apex, in both implementations alike
        rtol = np.where(y - 1 >= 1e-5, 1e-13, 1e-9)
        atol = 1e-13 * np.max(np.abs(FIRST["beta"][k]))
        assert np.all(np.abs(got - FIRST["beta"][k]) <= rtol * np.abs(FIRST["beta"][k]) + atol), k


def test_quadstep_matches_the_toolbox_to_its_tolerance():
    for k in range(FIRST["rs"].size):
        rs, rr, zs, zr, nu, s, c = _case(k)
        got = _quadstep(np.atleast_1d(FIRST["qa"][k]).astype(float), np.atleast_1d(FIRST["qb"][k]).astype(float),
                        np.atleast_1d(FIRST["qfa"][k]).astype(float), np.atleast_1d(FIRST["qfc"][k]).astype(float),
                        np.atleast_1d(FIRST["qfb"][k]).astype(float), 1e-11, rs, rr, zs, zr, nu, s, c)
        np.testing.assert_allclose(got[0], FIRST["qout"][k], rtol=0, atol=1e-9 * max(abs(FIRST["qout"][k]), 1e-12))


def test_wedge1st_ir_matches_the_toolbox():
    fs, c = float(FIRST["fs"]), float(FIRST["c"])
    for k in range(FIRST["rs"].size):
        f = {n: float(FIRST[n][k]) for n in ("closwedang", "rs", "thetas", "zs", "rr", "thetar", "zr", "r_irstart")}
        ir, initdelay, singular, zfirst = wedge1st_ir(
            fs, c, f["closwedang"], f["rs"], f["thetas"], f["zs"], f["rr"], f["thetar"], f["zr"],
            FIRST["zw"][k].astype(float), f["r_irstart"])
        ref = np.atleast_1d(FIRST["ir"][k]).astype(float)
        assert ir.shape == ref.shape, k
        assert np.all(np.isfinite(ir)), k
        ok = np.isfinite(ref)
        np.testing.assert_allclose(ir[ok], ref[ok], rtol=0, atol=1e-9 * max(np.max(np.abs(ref[ok])), 1e-30),
                                   err_msg=str(k))
        assert np.isclose(initdelay, FIRST["initdelay"][k], rtol=1e-12, atol=1e-12)
        np.testing.assert_array_equal(singular, FIRST["singular"][k].astype(bool))
        if np.isnan(FIRST["zfirst"][k]):
            assert zfirst is None
        else:
            assert np.isclose(zfirst, FIRST["zfirst"][k], rtol=1e-12, atol=1e-12), k


def test_coordtrans1_matches_the_toolbox():
    for k in range(SECOND["S"].shape[0]):
        r, t, z = _coordtrans1(SECOND["e2"][k], SECOND["e1"][k], SECOND["n1"][k])
        np.testing.assert_allclose(np.stack([r, t, z], axis=1), SECOND["cylE2_r1"][k], atol=1e-12)


def test_wedge2nd_ir_matches_the_toolbox():
    c, fs = float(SECOND["c"]), float(SECOND["fs"])
    for k in range(SECOND["S"].shape[0]):
        lengths = SECOND["lengths"][k].astype(float)
        steps, dz = element_grid(lengths, c, fs)
        np.testing.assert_allclose(dz, SECOND["dz"][k], rtol=1e-14)
        ir = wedge2nd_ir(SECOND["cylS"][k], SECOND["cylR"][k], SECOND["cylE2_r1"][k], SECOND["cylE1_r2"][k],
                         np.pi / np.array([SECOND["theta_w1"][k], SECOND["theta_w2"][k]], dtype=float),
                         np.array([[0.0, lengths[0]], [0.0, lengths[1]]]),
                         dz, steps, bool(SECOND["along"][k]), 0.0, c, fs)
        ref = np.atleast_1d(SECOND["ir"][k]).astype(float)
        assert ir.shape == ref.shape, k
        # conditioning bound of the ill-conditioned non-in-plane cases (one-ulp input perturbation: 6.9e-10 of peak)
        np.testing.assert_allclose(ir, ref, rtol=0, atol=1e-9 * max(np.max(np.abs(ref)), 1e-30), err_msg=str(k))


def test_toolbox_cyl_matches_edcoordtrans1_on_box_edges():
    for k in range(SECOND["S"].shape[0]):
        p, q = SECOND["e1"][k]
        axis = (q - p) / np.linalg.norm(q - p)
        n = SECOND["n1"][k]
        face_a = np.cross(n, axis)
        face_b = -n
        for edge in (Edge(p, q, face_a, face_b, 1.5 * np.pi), Edge(q, p, face_a, face_b, 1.5 * np.pi)):
            np.testing.assert_allclose(
                toolbox_cyl(edge, SECOND["S"][k][None, :])[0], SECOND["cylS"][k], atol=1e-12)


def object_room(kind, lo, hi, rot_deg):
    """The fixture's object in a 400 m enclosure that absorbs everything."""
    big = np.array([[-200, -200, -200], [200, -200, -200], [200, 200, -200], [-200, 200, -200],
                    [-200, -200, 200], [200, -200, 200], [200, 200, 200], [-200, 200, 200]], float)
    room_f = [(0, 3, 7, 4), (1, 5, 6, 2), (0, 4, 5, 1), (3, 2, 6, 7), (0, 1, 2, 3), (4, 7, 6, 5)]
    if kind == 0:
        v = np.array([[lo[0], lo[1], lo[2]], [hi[0], lo[1], lo[2]], [hi[0], hi[1], lo[2]], [lo[0], hi[1], lo[2]],
                      [lo[0], lo[1], hi[2]], [hi[0], lo[1], hi[2]], [hi[0], hi[1], hi[2]], [lo[0], hi[1], hi[2]]])
        f = [(0, 3, 2, 1), (4, 5, 6, 7), (0, 1, 5, 4), (1, 2, 6, 5), (2, 3, 7, 6), (3, 0, 4, 7)]
    else:
        v = np.array([[lo[0], lo[1], lo[2]], [hi[0], lo[1], lo[2]], [lo[0], hi[1], lo[2]],
                      [lo[0], lo[1], hi[2]], [hi[0], lo[1], hi[2]], [lo[0], hi[1], hi[2]]])
        f = [(0, 2, 1), (3, 4, 5), (0, 1, 4, 3), (1, 2, 5, 4), (2, 0, 3, 5)]
    a = np.radians(rot_deg)
    rot = np.array([[np.cos(a), -np.sin(a), 0], [np.sin(a), np.cos(a), 0], [0, 0, 1]])
    centre = (np.asarray(lo) + np.asarray(hi)) / 2.0
    v = (v - centre) @ rot.T + centre
    faces = tuple(room_f + [tuple(8 + i for i in face) for face in f])
    names = ("absorber",) * 6 + ("object",) * len(f)
    mats = {"absorber": Material(np.linspace(0.999, 1.0, 8), BANDS.copy()),
            "object": Material(np.linspace(0.0, 1e-6, 8), BANDS.copy())}
    return MeshGeometry(np.vstack([big, v]), faces, names, mats, obstacles=("object",))


def plate_room(corners):
    """A free thin plate (one polygon, knife edges) in the enclosure of object_room."""
    box = object_room(0, np.zeros(3), np.ones(3), 0.0)
    mats = {"absorber": Material(np.linspace(0.999, 1.0, 8), BANDS.copy()),
            "object": Material(np.linspace(0.0, 1e-6, 8), BANDS.copy())}
    return MeshGeometry(np.vstack([box.vertices[:8], corners]), tuple(list(box.faces[:6]) + [(8, 9, 10, 11)]),
                        ("absorber",) * 6 + ("object",), mats, obstacles=("object",))


def test_second_order_of_a_thin_plate_matches_the_toolbox_time_domain():
    # EDmain_convex modeltype 'singleplate' (validation/btms/plate_td.m, eval_plate.py): the toolbox doubles a
    # thin plate's along-plane edge-to-edge term for the equal path on the rear side (EDmakeHODirs.m, boostfactor)
    pl = loadmat(PLATE, squeeze_me=True)
    spec = RoomSpec(geometry=plate_room(pl["corners"]), source=pl["S"], receiver=pl["R"], air_absorption=False,
                    speed_of_sound=float(pl["c"]))
    n = 1 << 14
    ours = np.zeros(n)
    for p in btms_paths(spec, max_order=0):
        if p.order == 2:
            ours[p.start:p.start + p.ir.size] += p.ir[:n - p.start]
    ref = np.zeros(n)
    ref[:pl["ir2"].size] = pl["ir2"]
    f = np.fft.rfftfreq(n, 1 / spec.fs)
    h, g = np.fft.rfft(ours), np.fft.rfft(ref)
    for fc in (62.5, 125, 250, 500, 1000, 2000, 4000, 8000):
        m = (f >= fc / np.sqrt(2)) & (f < fc * np.sqrt(2))
        db = 10 * np.log10(np.mean(np.abs(h[m]) ** 2) / np.mean(np.abs(g[m]) ** 2))
        assert abs(db) < 0.1, fc


def test_second_order_matches_the_frequency_domain_reference():
    fd = loadmat(FD, squeeze_me=True)
    for k in range(fd["S"].shape[0]):
        geo = object_room(int(fd["kind"][k]), fd["lo"][k], fd["hi"][k], float(fd["rot_deg"][k]))
        spec = RoomSpec(geometry=geo, source=fd["S"][k], receiver=fd["R"][k], air_absorption=False,
                        speed_of_sound=float(fd["c"]))
        n = 1 << 14
        second = [p for p in btms_paths(spec, max_order=0) if p.order == 2]
        w = encode_btms(second, 0, n, spec.fs, normalization="NM")[:, 0] * 4 * np.pi
        h = np.fft.rfft(w, n)
        f = np.fft.rfftfreq(n, 1 / spec.fs)
        t = np.arange(n) / spec.fs
        h3 = np.abs(np.exp(-2j * np.pi * np.outer(fd["f3"], t)) @ w) ** 2
        for b, fc in enumerate(fd["octaves"]):
            m = (f >= fc / np.sqrt(2)) & (f < fc * np.sqrt(2))
            ours = 10 * np.log10(np.mean(np.abs(h[m]) ** 2))
            assert abs(ours - fd["td_db"][k][b]) < 0.1, ("toolbox TD", k, fc)
            if fc <= 4000:
                ours3 = 10 * np.log10(np.mean(h3[3 * b:3 * b + 3]))
                assert abs(ours3 - fd["ref_db"][k][b]) < 0.5, ("FD", k, fc)
